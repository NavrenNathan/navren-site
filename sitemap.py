#!/usr/bin/env python3
"""Rebuilds sitemap.xml from the pages themselves.

    python3 sitemap.py

Run it after committing page changes. Every root *.html page is listed
unless it carries a robots noindex tag, so the sitemap and the noindex tags
can never disagree. <lastmod> is the date of the last commit that touched
the file, so commit first, then run this, then commit the sitemap.
Standard library only.
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SITE = "https://navrenagency.com"
SKIP = {"404.html", "font-preview.html", "blog-post-template.html"}

# Relative weight in the sitemap. Pages not listed get DEFAULT.
PRIORITY = {
    "index": "1.0", "contact": "0.9", "services": "0.8", "approach": "0.8",
    "who-we-help": "0.8", "questionnaire": "0.8", "about": "0.7",
    "small-business-initiative": "0.7",
}
DEFAULT = "0.6"


def lastmod(path):
    out = subprocess.run(
        ["git", "log", "-1", "--format=%cs", "--", path.name],
        cwd=ROOT, capture_output=True, text=True,
    ).stdout.strip()
    return out or None


def main():
    rows = []
    for path in sorted(ROOT.glob("*.html")):
        if path.name in SKIP:
            continue
        if re.search(r'<meta name="robots" content="[^"]*noindex', path.read_text()):
            continue
        page = path.stem
        loc = SITE + "/" if page == "index" else f"{SITE}/{page}"
        mod = lastmod(path)
        rows.append(
            "  <url>\n"
            f"    <loc>{loc}</loc>\n"
            + (f"    <lastmod>{mod}</lastmod>\n" if mod else "")
            + f"    <priority>{PRIORITY.get(page, DEFAULT)}</priority>\n"
            "  </url>"
        )
    xml = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- Generated by sitemap.py: every root page without a noindex tag.\n"
        "     Do not edit by hand; re-run the script instead. -->\n"
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(rows)
        + "\n</urlset>\n"
    )
    (ROOT / "sitemap.xml").write_text(xml)
    print(f"  {len(rows)} pages written to sitemap.xml")


if __name__ == "__main__":
    main()
